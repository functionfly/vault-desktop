#!/usr/bin/env bash
# Step 4 of the vault desktop launch checklist: publish an update to
# the R2 bucket provisioned by `provision-r2-bucket.sh`.
#
# Usage (from the build host, after sourcing `load-updater-env.sh`):
#
#   ./scripts/release/publish-update.sh <channel> <version> \
#       <side-car> <side-car.sig> [target[,target...]]
#
# Example:
#
#   ./scripts/release/publish-update.sh stable 0.1.1 \
#       target/release/bundle/appimage/functionfly-vault-desktop_0.1.1_amd64.AppImage.tar.gz \
#       target/release/bundle/appimage/functionfly-vault-desktop_0.1.1_amd64.AppImage.tar.gz.sig \
#       linux-x86_64
#
# `target` is the platform key `tauri-plugin-updater` looks up in the
# manifest's `platforms` map. It is OPTIONAL: when omitted the key is
# derived from the side-car filename. Pass it explicitly in CI — the
# filename heuristic is a convenience for humans, not a contract.
#
# A comma-separated list publishes one archive under several keys. That
# is how the macOS universal build is served: the archive is the same
# file, but an Apple-Silicon client looks up `darwin-aarch64` and an
# Intel client looks up `darwin-x86_64`.
#
# Side effects:
#   1. Uploads the side-car archive + .sig to
#      vault/<channel>/<version>/…
#   2. Computes + uploads `vault/<channel>/manifest.json` containing the
#      absolute versioned archive URLs, the real signature payload, and
#      the per-platform entries `tauri-plugin-updater` expects
#   3. Marks `manifest.json` itself as the current per-channel index
#      (it lives at vault/<channel>/manifest.json; the
#      `vault/<channel>/<version>/…` archives are the side-cars it
#      points at)
#
# Re-running the script for a second platform MERGES that platform into
# the existing manifest, so a three-platform release is three calls that
# build up one manifest. The merge is version-scoped: a manifest for a
# different version is replaced wholesale rather than merged, because a
# stale platform entry would otherwise point at an older release.
#
# Pre-flight:
#   - R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY, R2_BUCKET
#   - python3 (or python) — the manifest is generated by a JSON encoder,
#     not by shell string interpolation
#   - The side-car archive must have been produced by `tauri build`
#     (which signs the .sig automatically when the signing env vars are
#     set)
#
# This script does NOT need the signing key: the `.sig` file is an input,
# not something it produces. It only needs upload credentials.
#
# ── NEVER REPUBLISH A VERSION ─────────────────────────────────────────────
#
# The artefact URL is `vault/<channel>/<version>/<filename>`. The CDN
# caches that URL, and the cache outlives the object: overwriting the
# object in R2 does NOT change what the edge serves.
#
# So republishing a version means the manifest can carry a NEW signature
# while the CDN still serves the OLD bytes. An installed client fetches
# both, verifies the bytes against the signature, and the update is
# REJECTED — with an error that looks like a signing fault rather than a
# cache fault.
#
# That is not theoretical. It happened during the v1.0.0 launch
# preparation: v1.0.0 was published with a broken build, fixed, and
# republished under the same version. R2 served the new bytes; the CDN
# kept serving the old ones for the whole TTL. A query-string bust
# (`?cb=1`) returned the new bytes, which is what identified it as edge
# caching rather than a failed upload.
#
# The fix is to publish a NEW VERSION. A new version is a new path, so
# it is a new cache entry. v1.0.1 exists for exactly this reason.
#
# If a version genuinely has to be republished, the CDN cache for
# `vault/<channel>/*` must be purged first. That needs a Cloudflare
# token with cache-purge permission, which the operator's current
# tokens do not have.
#
# `render-manifest.py --repoint` (gated behind VAULT_UPDATER_REPOINT)
# exists for the same reason: repointing a LIVE version's URL is
# refused by default, because clients that already cached the manifest
# would then be sent to bytes they have not seen.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

usage() {
  cat >&2 <<EOF
usage: $0 <channel> <version> <side-car> <side-car.sig> [target[,target...]]
  channel:       one of: stable | beta
  version:       semver, e.g. 0.1.1
  side-car:      path to the .tar.gz / .nsis.zip archive produced by tauri build
  signature:     path to the matching .sig file (produced by tauri build)
  target:        optional platform key(s), comma separated.
                 Valid keys: <os>-<arch>[-<installer>] where
                   os        = linux | darwin | windows
                   arch      = x86_64 | aarch64 | i686 | armv7 | riscv64
                   installer = appimage | deb | rpm | app | msi | nsis
                 e.g. linux-x86_64, darwin-aarch64,darwin-x86_64
                 When omitted it is derived from the side-car filename.
EOF
  exit 64
}

# ── Arg parsing + pre-flight ───────────────────────────────────────────
[[ $# -ge 4 && $# -le 5 ]] || usage

CHANNEL="$1"
VERSION="$2"
SIDECAR_PATH="$3"
SIG_PATH="$4"
TARGETS_ARG="${5:-}"

if [[ "$CHANNEL" != "stable" && "$CHANNEL" != "beta" ]]; then
  echo "publish-update: channel must be stable or beta, got: $CHANNEL" >&2
  exit 1
fi

if ! [[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+([+-][A-Za-z0-9.-]+)?$ ]]; then
  echo "publish-update: version must be semver, got: $VERSION" >&2
  exit 1
fi

if [[ ! -s "$SIDECAR_PATH" ]]; then
  echo "publish-update: side-car not found or empty: $SIDECAR_PATH" >&2
  exit 1
fi
if [[ ! -s "$SIG_PATH" ]]; then
  echo "publish-update: signature not found or empty: $SIG_PATH" >&2
  exit 1
fi

R2_BUCKET="${R2_BUCKET:-functionfly-vault-updates}"
R2_REGION="${R2_REGION:-auto}"

for v in R2_ACCOUNT_ID R2_ACCESS_KEY_ID R2_SECRET_ACCESS_KEY; do
  if [[ -z "${!v:-}" ]]; then
    echo "publish-update: $v is required (export R2_* in CI, or source scripts/release/load-updater-env.sh)" >&2
    exit 1
  fi
done

if ! command -v aws >/dev/null 2>&1; then
  echo "publish-update: the aws CLI is required (R2 is S3-compatible)" >&2
  exit 1
fi

# The manifest is produced by a real JSON encoder. Shell-quoting a
# release-notes string into JSON is how the previous manifest ended up
# with a single-quoted `notes` value that no client could parse.
PYTHON=""
for candidate in python3 python; do
  if command -v "$candidate" >/dev/null 2>&1; then
    PYTHON="$candidate"
    break
  fi
done
if [[ -z "$PYTHON" ]]; then
  echo "publish-update: python3 (or python) is required to generate the manifest" >&2
  exit 1
fi

# `R2_ENDPOINT_OVERRIDE` lets the smoke test (and local dev) route
# to a local mock R2 instead of the real Cloudflare endpoint. When
# unset we use the canonical R2 endpoint derived from `R2_ACCOUNT_ID`.
if [[ -n "${R2_ENDPOINT_OVERRIDE:-}" ]]; then
  ENDPOINT="$R2_ENDPOINT_OVERRIDE"
else
  ENDPOINT="https://${R2_ACCOUNT_ID}.r2.cloudflarestorage.com"
fi
export AWS_ACCESS_KEY_ID="$R2_ACCESS_KEY_ID"
export AWS_SECRET_ACCESS_KEY="$R2_SECRET_ACCESS_KEY"
export AWS_DEFAULT_REGION="$R2_REGION"

# ── Resolve the platform key(s) ────────────────────────────────────────
# The plugin looks up `{os}-{arch}-{bundle_type}` first and then
# `{os}-{arch}` in the manifest's `platforms` map. The bundle type is
# part of the key because a `.deb` user must be offered the `.deb`
# archive, not the AppImage that shares its architecture.
TARGET_PATTERN='^(linux|darwin|windows)-(x86_64|aarch64|i686|armv7|riscv64)(-(appimage|deb|rpm|app|msi|nsis))?$'

if [[ -z "$TARGETS_ARG" ]]; then
  TARGETS_ARG="$("$PYTHON" "$SCRIPT_DIR/updater-targets.py" "$(basename "$SIDECAR_PATH")")" || {
    echo "publish-update: could not derive the platform key(s) from '$(basename "$SIDECAR_PATH")'." >&2
    echo "  Pass them explicitly, e.g. ... <side-car> <sig> linux-x86_64" >&2
    exit 1
  }
  echo "publish-update: derived platform key(s) from the file name: ${TARGETS_ARG}" >&2
fi

IFS=',' read -r -a TARGETS <<< "$TARGETS_ARG"
[[ ${#TARGETS[@]} -gt 0 ]] || {
  echo "publish-update: no platform key resolved" >&2
  exit 1
}
for t in "${TARGETS[@]}"; do
  if ! [[ "$t" =~ $TARGET_PATTERN ]]; then
    echo "publish-update: invalid platform key '${t}'." >&2
    echo "  Expected <os>-<arch>[-<installer>], e.g. linux-x86_64" >&2
    exit 1
  fi
done

# ── Paths ──────────────────────────────────────────────────────────────
#
# The ARCHIVE IS RENAMED BEFORE IT IS PUBLISHED.
#
# Tauri's bundler names the Windows installers after the product name,
# which contains a space: `FunctionFly Vault_1.0.0_x64-setup.exe`. A
# space is not fetchable as part of a URL — the client requests
# `.../FunctionFly%20Vault_1.0.0_x64-setup.exe`, the CDN has no such
# key, and the update fails with a 404 that looks like a broken channel
# rather than a broken filename.
#
# So the name is normalised to something URL-safe before it becomes an
# S3 key or a URL. This is safe: the signature covers the BYTES, not
# the name. `src-tauri/tests/updater_artifact_contract.rs` verifies a
# real artefact's signature with the same minisign implementation the
# plugin uses at runtime.
#
# The transform is deliberately narrow: spaces become underscores and
# anything outside `[A-Za-z0-9._-]` is dropped. It must be stable, so
# the same artefact always publishes under the same key.
normalise_name() {
  local name="$1"
  name="${name// /_}"
  # Drop anything that is not URL-safe in a path segment.
  name="$(printf '%s' "$name" | tr -cd 'A-Za-z0-9._-')"
  printf '%s' "$name"
}

SOURCE_ARCHIVE_NAME="$(basename "$SIDECAR_PATH")"
ARCHIVE_NAME="$(normalise_name "$SOURCE_ARCHIVE_NAME")"
SIG_NAME="$(basename "$SIG_PATH")"

if [[ "$SIG_NAME" != "${SOURCE_ARCHIVE_NAME}.sig" ]]; then
  echo "publish-update: signature '${SIG_NAME}' does not match side-car '${SOURCE_ARCHIVE_NAME}'." >&2
  echo "  Expected the .sig to sit next to the archive with the same basename." >&2
  exit 1
fi

WORK_DIR="$(mktemp -d)"
cleanup() { rm -rf "$WORK_DIR"; }
trap cleanup EXIT

if [[ "$ARCHIVE_NAME" == "$SOURCE_ARCHIVE_NAME" ]]; then
  # Publish under the source name when it is already safe.
  PUBLISHED_ARCHIVE="$SIDECAR_PATH"
  PUBLISHED_SIG="$SIG_PATH"
else
  # Copy to the normalised name, so the uploaded object's key and its
  # contents agree.
  PUBLISHED_ARCHIVE="$WORK_DIR/${ARCHIVE_NAME}"
  PUBLISHED_SIG="$WORK_DIR/${ARCHIVE_NAME}.sig"
  cp "$SIDECAR_PATH" "$PUBLISHED_ARCHIVE"
  cp "$SIG_PATH" "$PUBLISHED_SIG"
  echo "publish-update: renamed for publication:" >&2
  echo "  ${SOURCE_ARCHIVE_NAME}" >&2
  echo "  -> ${ARCHIVE_NAME}" >&2
fi

PUBLIC_BASE="${VAULT_UPDATER_PUBLIC_BASE:-https://updates.functionfly.com/vault/${CHANNEL}}"
SIDECAR_KEY="vault/${CHANNEL}/${VERSION}/${ARCHIVE_NAME}"
SIG_KEY="vault/${CHANNEL}/${VERSION}/${ARCHIVE_NAME}.sig"
MANIFEST_KEY="vault/${CHANNEL}/manifest.json"
# The version index is the channel's HISTORY: every published version with
# its notes and its per-platform files. The manifest above describes only
# the newest version (the plugin deliberately discards a previous
# version's entries), so the marketing site's downloads page reads this
# document to list every version with its features.
VERSIONS_KEY="vault/${CHANNEL}/versions.json"
ARCHIVE_URL="${PUBLIC_BASE}/${VERSION}/${ARCHIVE_NAME}"

EXISTING_MANIFEST=""
if aws s3api get-object \
      --bucket "$R2_BUCKET" \
      --key "$MANIFEST_KEY" \
      "$WORK_DIR/existing.json" \
      --endpoint-url "$ENDPOINT" >/dev/null 2>&1; then
  EXISTING_MANIFEST="$WORK_DIR/existing.json"
fi

EXISTING_VERSIONS=""
if aws s3api get-object \
      --bucket "$R2_BUCKET" \
      --key "$VERSIONS_KEY" \
      "$WORK_DIR/existing-versions.json" \
      --endpoint-url "$ENDPOINT" >/dev/null 2>&1; then
  EXISTING_VERSIONS="$WORK_DIR/existing-versions.json"
fi

# ── Build the manifest ─────────────────────────────────────────────────
# The manifest contract lives in `render-manifest.py` so that
# `publish-update.test.sh` can assert its semantics on any machine,
# without an S3 endpoint or the AWS CLI.
#
# Every value is passed with the `--name=value` form so that a release
# note beginning with a dash cannot be mistaken for a flag.
RENDER_ARGS=(
  "--version=${VERSION}"
  "--pub-date=$(date -u +"%Y-%m-%dT%H:%M:%SZ")"
  "--notes=${NOTES:-vault ${VERSION} (channel: ${CHANNEL})}"
  "--url=${ARCHIVE_URL}"
  "--signature-file=${PUBLISHED_SIG}"
  "--targets=${TARGETS_ARG}"
  "--out=${WORK_DIR}/manifest.json"
)
if [[ -n "$EXISTING_MANIFEST" ]]; then
  RENDER_ARGS+=("--existing=${EXISTING_MANIFEST}")
fi

# The version index is rendered by a separate script from the manifest:
# the manifest keeps ONE version (the newest) and the index keeps them
# ALL. Their merge rules differ, so their renderers differ.
VERSIONS_ARGS=(
  "--version=${VERSION}"
  "--pub-date=$(date -u +"%Y-%m-%dT%H:%M:%SZ")"
  "--notes=${NOTES:-vault ${VERSION} (channel: ${CHANNEL})}"
  "--url=${ARCHIVE_URL}"
  "--signature-file=${PUBLISHED_SIG}"
  "--targets=${TARGETS_ARG}"
  "--channel=${CHANNEL}"
  "--out=${WORK_DIR}/versions.json"
)
if [[ -n "$EXISTING_VERSIONS" ]]; then
  VERSIONS_ARGS+=("--existing=${EXISTING_VERSIONS}")
fi

# Repairing a publication that was broken and therefore never reachable
# (a manifest published against the wrong hostname, say) requires the
# target's URL to change for a version that is already published. The
# renderer refuses that by default, because repointing a LIVE version
# would serve different bytes to clients that already cached the
# manifest. The operator opts in explicitly.
if [[ "${VAULT_UPDATER_REPOINT:-false}" == "true" ]]; then
  RENDER_ARGS+=("--repoint")
  echo "publish-update: REPOINT enabled — the target URL will be replaced for version ${VERSION}" >&2
fi

"$PYTHON" "$SCRIPT_DIR/render-manifest.py" "${RENDER_ARGS[@]}"
"$PYTHON" "$SCRIPT_DIR/render-versions.py" "${VERSIONS_ARGS[@]}"

echo "publish-update: manifest targets: ${TARGETS_ARG}" >&2

# ── Upload side-car + signature to the versioned path ────────────────
echo "── vault uploader ──"
echo "  channel:  $CHANNEL"
echo "  version:  $VERSION"
echo "  targets:  ${TARGETS_ARG}"
echo "  side-car: $SIDECAR_PATH"
echo "  sig:      $SIG_PATH"
echo "  bucket:   $R2_BUCKET"
echo

echo "→ uploading side-car to s3://${R2_BUCKET}/${SIDECAR_KEY}"
aws s3 cp "$PUBLISHED_ARCHIVE" "s3://${R2_BUCKET}/${SIDECAR_KEY}" \
  --endpoint-url "$ENDPOINT" \
  --content-type application/octet-stream >/dev/null
echo "  ok"

echo "✓ uploading signature to s3://${R2_BUCKET}/${SIG_KEY}"
aws s3 cp "$PUBLISHED_SIG" "s3://${R2_BUCKET}/${SIG_KEY}" \
  --endpoint-url "$ENDPOINT" \
  --content-type application/octet-stream >/dev/null
echo "  ok"

echo "→ uploading manifest to s3://${R2_BUCKET}/${MANIFEST_KEY}"
aws s3 cp "$WORK_DIR/manifest.json" "s3://${R2_BUCKET}/${MANIFEST_KEY}" \
  --endpoint-url "$ENDPOINT" \
  --content-type application/json >/dev/null
echo "  ok"

echo "→ uploading version index to s3://${R2_BUCKET}/${VERSIONS_KEY}"
aws s3 cp "$WORK_DIR/versions.json" "s3://${R2_BUCKET}/${VERSIONS_KEY}" \
  --endpoint-url "$ENDPOINT" \
  --content-type application/json >/dev/null
echo "  ok"

echo
echo "── Done ──"
echo "  side-car:  $ARCHIVE_URL"
echo "  signature: ${PUBLIC_BASE}/${VERSION}/${SIG_NAME}"
echo "  manifest:  ${PUBLIC_BASE}/manifest.json"
echo "  versions:  ${PUBLIC_BASE}/versions.json"
echo
echo "Run \`cargo-tauri signer verify -p <pubkey> <side-car> <sig>\` locally"
echo "to re-verify the signature before declaring an install for manual QA."
